def test_yara_scan_via_api_includes_new_rules():
    # File_Suspicious_PE should hit via POST /api/yara/scan
    r = client.post("/api/yara/scan", json={"content": "file C:\\Temp\\malware.exe yara test", "filename":"x.txt"})
    assert r.status_code==200
    j = r.json()
    # new rule uses malware.exe string, should hit at least one
    assert j["hit_count"] >= 1

def test_detect_combines_sigma_behavioral():
    payload = {"type":"process","processes":[{"pid":5678,"name":"svchost.exe","ppid_anomaly":True,"yara_hit":"JOCKY_DEMO_MARKER"}]}
    findings = detect(payload)
    # should have both sigma and behavioral
    assert any(f["source"]=="sigma" for f in findings)
    assert any(f["source"]=="behavioral" for f in findings)
    # each finding has mitre and severity per FORENSICS §31
    for f in findings:
        assert "mitre" in f and "severity" in f

def test_api_detect_enriched():
    # POST /api/detect should return yara_used + hits with mitre per updated engine
    r = client.post("/api/detect", json={"type":"process","ppid_anomaly": True, "processes":[{"ppid_anomaly": True}]})
    assert r.status_code==200
    j = r.json()
    assert "hits" in j and "risk" in j
    assert "yara_hits" in j
    # Sigma hit for ppid anomaly via detect path (through yara_scan_content + detect) is still covered via direct engine test above

def test_risk_deterministic_via_detection():
    # Same evidence → same risk per FORENSICS §45
    payload = {"type":"file","yara_hit":"JOCKY_DEMO_MARKER","hashes":{"sha256":"abc"}}
    from backend.app.main import calc_risk
    assert calc_risk(payload) == calc_risk(payload)
    assert calc_risk(payload) >= 35  # file yara weight
